<h2>§ 1. Postanowienia wstępne</h2>
<ol>
    <li>Regulamin określa zasady korzystania z serwisu <strong>pnedu.pl</strong> oraz zamawiania usług szkoleniowych i treści cyfrowych.</li>
    <li>Usługodawcą jest <strong>Platforma Nowoczesnej Edukacji Waldemar Grabowski</strong>, ul. Andrzeja Zamoyskiego 30/14, 09-320 Bieżuń, NIP 7392137630, e-mail: <a href="mailto:kontakt@pnedu.pl">kontakt@pnedu.pl</a>, tel. +48 501 654 274 (dalej: „PNE”).</li>
    <li>Regulamin jest udostępniany nieodpłatnie przed zawarciem umowy w formie umożliwiającej jego zapisanie i odtworzenie.</li>
</ol>

<h2>§ 2. Usługi</h2>
<ol>
    <li>PNE oferuje w szczególności odpłatne szkolenia online na żywo i stacjonarne, dostęp do nagrań, materiałów i kursów online oraz bezpłatne webinary.</li>
    <li>Program, termin, forma, cena, okres dostępu oraz zakres materiałów są wskazane w ofercie danego szkolenia i podsumowaniu zamówienia.</li>
    <li>Do udziału online potrzebne są urządzenie z dostępem do Internetu, aktualna przeglądarka, aktywny adres e-mail i możliwość odtwarzania treści audio-wideo.</li>
</ol>

<h2>§ 3. Zawarcie umowy</h2>
<ol>
    <li>Przed złożeniem zamówienia Zamawiający otrzymuje podsumowanie wybranego świadczenia, całkowitej ceny i sposobu płatności oraz dostęp do niniejszego Regulaminu.</li>
    <li>Zamówienie odpłatne zostaje złożone przez użycie przycisku „Zamówienie z obowiązkiem zapłaty”. Umowa zostaje zawarta z chwilą przyjęcia zamówienia przez system PNE, co PNE potwierdza na podany adres e-mail.</li>
    <li>Zamawiający podaje dane prawdziwe i potrzebne do realizacji zamówienia. Jeżeli zgłasza inną osobę jako uczestnika, wskazuje dane potrzebne do organizacji jej udziału.</li>
</ol>

<h2>§ 4. Ceny i płatności</h2>
<ol>
    <li>Łączna cena brutto oraz sposób i termin płatności są wskazane w podsumowaniu zamówienia.</li>
    <li>Płatność następuje na podstawie faktury z terminem wskazanym w zamówieniu albo online za pośrednictwem PayU lub Paynow.</li>
    <li>Przy fakturze z odroczonym terminem PNE może zapewnić udział w szkoleniu i dostęp do objętych ofertą zasobów przed otrzymaniem płatności. Odroczenie płatności nie zwalnia z obowiązku zapłaty.</li>
    <li>PNE korzysta ze zwolnienia z VAT w zakresie wynikającym z obowiązujących przepisów. Cena prezentowana klientowi jest ceną do zapłaty.</li>
</ol>

<h2>§ 5. Realizacja</h2>
<ol>
    <li>Szkolenie jest realizowane w terminie i formie wskazanych w ofercie i podsumowaniu zamówienia. Dane dostępowe do szkolenia online są przekazywane na adres uczestnika.</li>
    <li>Jeżeli oferta obejmuje nagranie, materiały, kurs online lub zaświadczenie, są one udostępniane na zasadach i przez okres wskazane w ofercie. Nagranie ze szkolenia na żywo jest zwykle udostępniane po zakończeniu spotkania.</li>
    <li>Zamawiający odpowiada za prawidłowość podanego adresu e-mail i numeru telefonu. PNE może skontaktować się telefonicznie w sprawach organizacyjnych, rozliczeniowych lub w razie problemu z kontaktem e-mail.</li>
</ol>

<h2>§ 6. Prawo odstąpienia</h2>
<ol>
    <li>Konsument może odstąpić od umowy zawartej na odległość w terminie 14 dni od jej zawarcia, składając PNE jednoznaczne oświadczenie. Wzór formularza znajduje się na stronie <a href="{{ route('withdrawal') }}">Odstąpienie od umowy</a>, ale jego użycie nie jest obowiązkowe.</li>
    <li>Jeżeli na wyraźne żądanie Konsumenta wykonywanie odpłatnej usługi rozpoczęło się przed upływem tego terminu, a Konsument odstąpi przed pełnym wykonaniem usługi, jest zobowiązany do zapłaty proporcjonalnie za świadczenie spełnione do chwili odstąpienia.</li>
    <li>Prawo odstąpienia w odniesieniu do odpłatnej usługi wygasa po jej pełnym wykonaniu, jeżeli przed rozpoczęciem świadczenia Konsument złożył wymagane prawem żądanie lub zgodę i przyjął do wiadomości skutek pełnego wykonania.</li>
    <li>Jeżeli odpłatna treść cyfrowa niedostarczana na nośniku materialnym ma zostać dostarczona przed upływem terminu odstąpienia, PNE rozpoczyna jej dostarczanie po uzyskaniu wyraźnej uprzedniej zgody Konsumenta i potwierdzenia przyjęcia do wiadomości skutku dla prawa odstąpienia.</li>
    <li>Postanowienia niniejszego paragrafu stosuje się również do osoby fizycznej prowadzącej działalność gospodarczą, gdy umowa jest bezpośrednio związana z jej działalnością, ale nie ma dla niej charakteru zawodowego w rozumieniu art. 7aa ustawy o prawach konsumenta.</li>
</ol>

<h2>§ 7. Reklamacje</h2>
<ol>
    <li>Reklamację można złożyć na adres <a href="mailto:kontakt@pnedu.pl">kontakt@pnedu.pl</a> lub adres PNE, podając informacje pozwalające zidentyfikować zamówienie i opis problemu. Reklamacja nie wymaga szczególnego formularza.</li>
    <li>PNE udziela Konsumentowi odpowiedzi w terminie 14 dni od otrzymania reklamacji, na papierze lub innym trwałym nośniku.</li>
    <li>PNE odpowiada wobec Konsumenta za zgodność usługi, treści cyfrowej lub usługi cyfrowej z umową na zasadach określonych w obowiązujących przepisach.</li>
</ol>

<h2>§ 8. Potwierdzenie na trwałym nośniku</h2>
<ol>
    <li>Po zawarciu umowy PNE przesyła Zamawiającemu potwierdzenie na podany adres e-mail.</li>
    <li>W przypadku Konsumenta potwierdzenie jest przekazywane w rozsądnym czasie, nie później niż przed rozpoczęciem świadczenia, i obejmuje informacje wymagane prawem, dane zamówienia oraz Regulamin właściwy dla tego zamówienia.</li>
    <li>Jeżeli Konsument złożył oświadczenie dotyczące wcześniejszego rozpoczęcia usługi lub dostarczenia treści cyfrowej, jego treść jest również potwierdzana w wiadomości.</li>
</ol>

<h2>§ 9. Odpowiedzialność i prawa autorskie</h2>
<ol>
    <li>Materiały są chronione prawem autorskim. Uczestnik otrzymuje niewyłączne prawo korzystania z nich na własne potrzeby, bez prawa dalszego rozpowszechniania.</li>
    <li>Odpowiedzialność PNE wobec podmiotów niebędących konsumentami ani przedsiębiorcami objętymi ochroną konsumencką może być ograniczona do wartości zamówienia, z wyjątkiem szkody wyrządzonej umyślnie i przypadków, w których prawo nie pozwala na takie ograniczenie.</li>
</ol>

<h2>§ 10. Dane osobowe</h2>
<p>Informacje o przetwarzaniu danych znajdują się w <a href="{{ route('rodo') }}">Informacji RODO</a> i <a href="{{ route('polityka-prywatnosci') }}">Polityce prywatności</a>.</p>

<h2>§ 11. Zmiany Regulaminu i postanowienia końcowe</h2>
<ol>
    <li>Do konkretnego zamówienia stosuje się wersję Regulaminu udostępnioną przed jego złożeniem i wskazaną w potwierdzeniu. Późniejsza zmiana nie narusza praw nabytych.</li>
    <li>Regulamin podlega prawu polskiemu. Spory rozstrzygają właściwe sądy powszechne z uwzględnieniem bezwzględnie obowiązujących praw konsumentów.</li>
</ol>
